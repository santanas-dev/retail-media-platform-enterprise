    tasks = []
    for t in extract_tasks():
        vb, ref, gate = accept_map[t["id"]]
        acc = {"check": t["acceptance_text"].split(";")[0].strip(), "verified_by": vb}
        if ref:
            acc["ref"] = ref
        entry = {
            "id": t["id"], "kind": t["kind"], "stage": t["stage"], "title": t["title"],
            "dependencies": t["deps"], "acceptance": [acc],
            "decision_status": "approved",
            "delivery_status": ("done" if t["id"] in DONE
                                else "in_progress" if t["id"] in IN_PROGRESS else "planned"),
            "notes": "полная приёмка — docs/audit/2026-08-26-roadmap-task-breakdown-final-candidate.md (+v2)",
        }
        if t["alias"]:
            entry["alias"] = t["alias"]
        if gate:
            entry["owner_gate"] = {"required": True, "reason": gate}
        if t["id"] in DONE:
            entry["evidence_refs"] = [
                {"kind": "command",
                 "ref": "python3 scripts/ci/check-roadmap-schema.py --self-test",
                 "status": "verified"},
                {"kind": "artifact",
                 "ref": "docs/architecture/rm-gov-001-roadmap-yaml-design-gate.md",
                 "status": "verified"},
            ]
