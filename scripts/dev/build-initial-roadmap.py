def classify(module, status, nextstep, seen_domains):
    """Deterministic disposition for one legacy row.

    Order matters: structural -> contradicted -> duplicate (narrow, name-only) ->
    deferred -> closed -> open work.
    """
    mod, st = _norm(module), _norm(status)
    blob = f"{mod} {st} {_norm(nextstep)}".lower()

    if mod.upper() == "SECTION":
        return "history", "структурный разделитель старого листа", None

    if mod in CONTRADICTED:
        return "drop-with-reason", CONTRADICTED[mod], None

    if mod in OVERRIDES:
        disp, reason, target = OVERRIDES[mod]
        return disp, f"[ручная поправка] {reason}", target

    # Duplicates are decided on the ROW NAME only, and only for domains the audit
    # actually proved duplicated. A broad match on free text would mislabel most rows.
    for group, pat in DUPLICATE_GROUPS.items():
        if re.search(pat, mod.lower()):
            if group in seen_domains:
                return ("deduplicate",
                        f"домен «{group}» уже описан строкой «{seen_domains[group]}»", None)
            seen_domains[group] = mod
            break

    if st.startswith("🚫"):
        return "history", "отложено решением владельца/ADR; §10 запрещает активацию без нового решения", None

    if st.startswith(OPEN_STATUS_PREFIXES):
        for pat, task in DOMAIN_TO_TASK:
            if re.search(pat, blob):
                return "migrate", "открытая работа перенесена в утверждённую задачу", task
        return ("history",
                OPEN_OUT, None)

    if st.startswith("✅") or st.startswith("🟡"):
        return "history", "работа закрыта; остаточных обязательств нет", None

    return "history", "нет остаточной работы, сопоставимой с утверждённой очередью", None


def build_manifest():
    wb = openpyxl.load_workbook(XLSX, data_only=True)
    entries, counts = [], Counter()

    tech = wb["Технический Roadmap"]
    seen = {}
    for r in tech.iter_rows(min_row=2):
        if not any(c.value for c in r):
            continue
        mod, st, nxt = r[0].value, r[1].value, r[3].value if len(r) > 3 else ""
        disp, reason, target = classify(mod, st, nxt, seen)
        kind = "section" if _norm(mod).upper() == "SECTION" else "technical"
        counts[f"{kind}:{disp}"] += 1
        e = dict([("source", "technical-sheet"), ("row", r[0].row),
                         ("name", _norm(mod)), ("legacy_status", _norm(st)),
                         ("disposition", disp), ("reason", reason)])
        if target:
            e["target"] = target
        entries.append(e)

    biz = wb["Бизнес-функции Roadmap"]
    seen_b = {}
    for r in biz.iter_rows(min_row=2):
        if not any(c.value for c in r):
            continue
        name, st = r[1].value, r[5].value if len(r) > 5 else ""
        nxt = r[10].value if len(r) > 10 else ""
        disp, reason, target = classify(name, st, nxt, seen_b)
        counts[f"business:{disp}"] += 1
        e = dict([("source", "business-sheet"), ("row", r[0].row),
                         ("name", _norm(name)), ("legacy_status", _norm(st)),
                         ("disposition", disp), ("reason", reason)])
        if target:
            e["target"] = target
        entries.append(e)

    return entries, counts



