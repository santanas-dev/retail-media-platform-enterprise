PREFIX = {"G": "GOV", "S": "STAB", "U": "UX", "B": "BIZ", "T": "TECH", "P": "PILOT", "E": "ENV"}


def _expand(token):
    """'G001–002' -> [RM-GOV-001, RM-GOV-002]; 'S010' -> [RM-STAB-010]; 'Gate G' -> [Gate-G]."""
    token = token.strip()
    if not token or token == "—":
        return []
    m = re.match(r"^Gate\s+([A-Z])$", token)
    if m:
        return [f"Gate-{m.group(1)}"]
    if token == "E0":
        return ["RM-ENV-001"]
    m = re.match(r"^([GSUBTPE])(\d{3})([AB]?)\s*[–-]\s*(\d{3})$", token)
    if m:
        pre, lo, _sfx, hi = m.groups()
        return [f"RM-{PREFIX[pre]}-{n:03d}" for n in range(int(lo), int(hi) + 1)]
    m = re.match(r"^([GSUBTPE])(\d{3})([AB]?)$", token)
    if m:
        pre, num, sfx = m.groups()
        return [f"RM-{PREFIX[pre]}-{num}{sfx}"]
    return []


def normalize_deps(raw):
    out = []
    # everything after '+' is an owner input/approval, not a dependency
    raw = raw.split("+")[0]
    for part in re.split(r",", raw):
        out.extend(_expand(part))
    seen, uniq = set(), []
    for d in out:
        if d not in seen:
            seen.add(d)
            uniq.append(d)
    return uniq


def extract_tasks():
    text = CANDIDATE.read_text(encoding="utf-8")
    stage, tasks = None, []
    for line in text.split("\n"):
        m = re.match(r"^## \d+\. (Этап [A-Z/0-9]+)", line)
        if m:
            stage = STAGES.get(m.group(1))
        r = re.match(
            r"^\|\s*\*\*(RM-[A-Z]+-\d+[AB]?)(?:\s*/\s*(A\w+))?\*\*\s*\|\s*([a-z\-]+)"
            r"\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*$", line)
        if r:
            tid, alias, kind, title, deps, acc = r.groups()
            tasks.append({"id": tid, "alias": alias, "kind": kind, "stage": stage,
                          "title": title, "deps": normalize_deps(deps),
                          "acceptance_text": acc})
    return tasks



